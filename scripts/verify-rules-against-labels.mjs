// Checks the numbers in every label-curated record against the FDA label the
// record cites (DailyMed setId): band thresholds must appear near a kidney
// term, and every amount/percentage/interval in the dose text must appear in
// the label. Writes docs/curation/label-text-audit.md.
//
//   npm run rules:verify-text                  (fetches missing labels)
//   npm run rules:verify-text -- --write-fixture  (also refreshes the CI fixture)
//
// Labels are cached in the git-ignored .cache/labels-by-setid/. Reads
// OPENFDA_API_KEY from .env.local when present; never prints it.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { labelCuratedRules } from "../src/data/renalRules/label-curated.js";
import { extractClaims, findClaim, normalizeLabelText } from "./lib/labelClaims.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CACHE_DIR = path.join(root, ".cache/labels-by-setid");
const REPORT = path.join(root, "docs/curation/label-text-audit.md");
const FIXTURE = path.join(root, "test/fixtures/label-claims.json");
const writeFixture = process.argv.includes("--write-fixture");
const EXCEPTIONS = JSON.parse(
  await readFile(path.join(root, "docs/curation/label-text-audit-exceptions.json"), "utf8")
);

await loadLocalEnv();
await mkdir(CACHE_DIR, { recursive: true });

const rows = [];
const fixture = {};
for (const record of labelCuratedRules) {
  const setId = record.sourceUrl.match(/setid=([\w-]+)/i)?.[1];
  const name = `${record.drugName} [${record.routes.join("/")}]`;
  const text = setId ? await loadLabelText(setId) : null;
  if (!text) {
    rows.push({ name, setId, status: "FETCH-FAILED", missing: [] });
    continue;
  }
  const normalized = normalizeLabelText(text);
  const results = extractClaims(record).map((claim) => ({ claim, found: findClaim(normalized, claim) }));
  const missing = results.filter((result) => !result.found).map((result) => result.claim.label);
  fixture[setId] = [
    ...new Set([...(fixture[setId] || []), ...results.filter((r) => r.found).map((r) => r.claim.key)]),
  ].sort();
  const exception = EXCEPTIONS[`${record.drugName}|${record.routes.join("/")}`];
  rows.push({
    name,
    setId,
    status: !missing.length ? "OK" : exception ? "HAND-CHECKED" : "MISSING",
    missing: exception && missing.length ? [...missing, `— ${exception}`] : missing,
  });
}

const counts = rows.reduce((acc, row) => ({ ...acc, [row.status]: (acc[row.status] || 0) + 1 }), {});
const lines = [
  "# Label-text audit of label-curated records",
  "",
  "Generated by `npm run rules:verify-text`. For every record in",
  "`src/data/renalRules/label-curated.js`, each band threshold must appear in the cited label",
  "near a kidney term, and each amount, percentage and interval in the dose text must appear",
  "in the label. Records whose claims are present in a form the check cannot see (for example a",
  "table with the unit in its header) are listed in `label-text-audit-exceptions.json` with the",
  "reason, and shown here as HAND-CHECKED.",
  "",
  `Records: ${rows.length} · ${Object.entries(counts)
    .map(([status, n]) => `${status}: ${n}`)
    .join(" · ")}`,
  "",
  "| Record | Status | Claims not found in label text |",
  "|---|---|---|",
  ...rows.map((row) => `| ${row.name} | ${row.status} | ${row.missing.join("; ")} |`),
  "",
];
await writeFile(REPORT, lines.join("\n"));
if (writeFixture) {
  await writeFile(FIXTURE, `${JSON.stringify(fixture, null, 0)}\n`);
}
console.log(`${rows.length} records · ${JSON.stringify(counts)} → ${path.relative(root, REPORT)}`);
for (const row of rows.filter((r) => r.status !== "OK")) {
  console.log(`  ${row.status.padEnd(12)} ${row.name}: ${row.missing.join("; ")}`);
}

async function loadLabelText(setId) {
  const file = path.join(CACHE_DIR, `${setId}.json`);
  try {
    return JSON.parse(await readFile(file, "utf8")).text;
  } catch {
    // Not cached yet.
  }
  const params = new URLSearchParams({ search: `set_id:"${setId}"`, limit: "1" });
  if (process.env.OPENFDA_API_KEY) {
    params.set("api_key", process.env.OPENFDA_API_KEY);
  }
  for (let attempt = 0; attempt < 3; attempt += 1) {
    let response;
    try {
      response = await fetch(`https://api.fda.gov/drug/label.json?${params}`);
    } catch {
      await new Promise((resolve) => setTimeout(resolve, 3_000));
      continue;
    }
    if (response.status === 429) {
      await new Promise((resolve) => setTimeout(resolve, 20_000));
      continue;
    }
    if (!response.ok) {
      return null;
    }
    const label = (await response.json()).results?.[0];
    if (!label) {
      return null;
    }
    const text = Object.entries(label)
      .filter(
        ([key, value]) =>
          Array.isArray(value) && typeof value[0] === "string" && !/^(?:spl_|package_|set_id|id$)/.test(key)
      )
      .map(([, value]) => value.join(" "))
      .join(" ");
    await writeFile(file, JSON.stringify({ setId, text }));
    return text;
  }
  return null;
}

// Reads KEY=value lines from the git-ignored .env.local (e.g. OPENFDA_API_KEY).
async function loadLocalEnv() {
  try {
    const text = await readFile(path.join(root, ".env.local"), "utf8");
    for (const line of text.split(/\r?\n/)) {
      const match = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*?)\s*$/);
      if (match && !process.env[match[1]]) {
        process.env[match[1]] = match[2].replace(/^["']|["']$/g, "");
      }
    }
  } catch {
    // No .env.local; runs within the keyless rate limit.
  }
}
