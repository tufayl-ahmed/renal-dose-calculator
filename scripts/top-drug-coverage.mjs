// Coverage of the 300 most-prescribed drugs (src/data/drugRank.js).
//
//   node scripts/top-drug-coverage.mjs          curated-record coverage only (offline)
//   node scripts/top-drug-coverage.mjs --live   also runs the full pipeline on live
//                                               openFDA labels for drugs without a record
//
// Writes docs/curation/top-drug-coverage.md. With --live it also writes
// src/data/nonSystemicDrugs.js (the autocomplete "Not applicable" badge);
// run `npm run coverage:index` after it.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TOP_DRUGS } from "../src/data/drugRank.js";
import { findCandidateRenalDoseGuidance, findCuratedRenalDoseGuidance } from "../src/curatedDoseRules.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const live = process.argv.includes("--live");
const resolveDosePayload = live ? (await import("../server/renalDose/pipeline.js")).resolveDosePayload : null;

const patient = {
  crcl: 25,
  egfr: 24,
  age: 70,
  sex: "male",
  weight: 70,
  creatinine: 2.6,
  dialysis: "none",
  indication: "any",
  formulation: "any",
};
const rows = [];
const nonSystemic = new Set();
for (const [index, name] of TOP_DRUGS.entries()) {
  const parts = name.split(";").map((part) => part.trim());
  const queries = [...new Set([parts.join(" and "), [...parts].reverse().join(" and ")])];
  let curated = "";
  for (const route of ["ORAL", "IV", "SC"]) {
    for (const query of queries) {
      const input = { ...patient, drugQuery: query, normalizedDrug: query, route };
      if (findCuratedRenalDoseGuidance(input)) {
        curated ||= `curated (${route})`;
      } else if (findCandidateRenalDoseGuidance(input)) {
        curated ||= `extracted (${route})`;
      }
    }
  }
  let runtime = "";
  if (live && !curated) {
    try {
      const payload = await resolveDosePayload({ patient: { ...patient, drug: queries[0], route: "ORAL" }, env: {} });
      runtime = `${payload.sourceMode} / ${payload.result?.status}`;
      if (payload.result?.status === "not_applicable") {
        // The label title ("Fluticasone Propionate") is how autocomplete lists it.
        nonSystemic.add(name);
        if (payload.label?.title) {
          nonSystemic.add(titleCase(payload.label.title));
        }
      }
    } catch (error) {
      runtime = `error: ${error.message}`;
    }
  }
  rows.push({ rank: index + 1, name, curated, runtime });
}

const covered = rows.filter((row) => row.curated).length;
const byRuntime = rows
  .filter((row) => row.runtime)
  .reduce((acc, row) => ({ ...acc, [row.runtime]: (acc[row.runtime] || 0) + 1 }), {});
const lines = [
  "# Coverage of the 300 most-prescribed drugs",
  "",
  "Generated by `node scripts/top-drug-coverage.mjs" + (live ? " --live" : "") + "` (patient: CrCl 25).",
  "",
  `Curated or extracted record: **${covered}/300**.`,
  "",
  ...(live
    ? [
        "What the live pipeline returns for the rest (oral route):",
        "",
        ...Object.entries(byRuntime)
          .sort((a, b) => b[1] - a[1])
          .map(([key, count]) => `- ${key}: ${count}`),
        "",
      ]
    : []),
  "| Rank | Drug | Record | Live result |",
  "|---|---|---|---|",
  ...rows.map((row) => `| ${row.rank} | ${row.name} | ${row.curated || "—"} | ${row.runtime || ""} |`),
  "",
];
await writeFile(path.join(root, "docs/curation/top-drug-coverage.md"), lines.join("\n"));
if (live) {
  const names = [...nonSystemic].sort((a, b) => a.localeCompare(b));
  await writeFile(
    path.join(root, "src/data/nonSystemicDrugs.js"),
    [
      "// Generated by `node scripts/top-drug-coverage.mjs --live`. Do not edit by hand.",
      "// Top-300 drugs the live label lookup found only in topical, eye, ear, nasal",
      "// or inhaled forms with no kidney text. Feeds the autocomplete badge only;",
      "// the dose card always comes from the live lookup.",
      `export const NON_SYSTEMIC_DRUGS = ${JSON.stringify(names, null, 2)};`,
      "",
    ].join("\n")
  );
}
console.log(`curated/extracted: ${covered}/300`);
if (live) {
  console.log(byRuntime);
}

function titleCase(value) {
  return String(value)
    .toLowerCase()
    .replace(/\b[a-z]/g, (letter) => letter.toUpperCase());
}
