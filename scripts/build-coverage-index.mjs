// Writes src/data/coverageIndex.js: a small lookup (normalized drug name ->
// best database status and routes) that lets autocomplete show coverage
// badges without loading the full rule database in the browser.
//
//   npm run coverage:index        (also run by candidates:extract)
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { buildCoverageIndex } from "./lib/coverageIndex.mjs";

const output = new URL("../src/data/coverageIndex.js", import.meta.url);
const index = buildCoverageIndex();
await writeFile(output, renderCoverageModule(index));
console.log(`Wrote ${Object.keys(index).length} names to ${fileURLToPath(output)}`);

export function renderCoverageModule(index) {
  return `// Generated by scripts/build-coverage-index.mjs. Do not edit by hand.
// status: v = clinician-verified, c = curated draft, e = auto-extracted.
export const COVERAGE_INDEX = ${JSON.stringify(index)};\n`;
}
